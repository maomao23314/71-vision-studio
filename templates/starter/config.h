/* ==========================================================================
 *  config.h —— 编译期契约（★ 唯一需要用户关心的配置）
 *  --------------------------------------------------------------------------
 *  设计理念对照：
 *    · 上手即用     → 整个环境只有这一个配置文件，且只有尺寸是必改项
 *    · 代码松耦合   → 本文件【不被环境库包含】，只影响 bind 与用户算法
 *    · 模拟单片机   → 这里的宏对应车载工程的摄像头分辨率
 *
 *  ★ 关于文件名：本文件叫 config.h。环境内部（bind 单元）按 scut_config.h
 *    引用它，构建脚本会自动生成一个只做转发的 scut_config.h 垫片，
 *    所以【两种命名都可用】，你保持 config.h 即可。
 *
 *  ★ 为什么这个文件不能"藏起来"：
 *      C 语言里数组大小必须是编译期常量。用户算法里到处是
 *          int left_line[SCUT_IMAGE_H];
 *      这类声明，所以尺寸契约必然暴露给用户。这是语言的硬约束，
 *      不是设计缺陷。我们的做法是把暴露面【压到最小】：
 *      只有本文件，且只有尺寸是必改的。
 *
 *  ★ 改本文件后：
 *      · bind 单元重编（几十行，瞬间）
 *      · 用户算法重编
 *      · 环境库【零重编】 ← 这是这套架构的核心收益
 * ========================================================================== */
#ifndef SCUT_CONFIG_H
#define SCUT_CONFIG_H

/* --------------------------------------------------------------------------
 * 摄像头图像尺寸（★ 单位：像素）
 *
 * MT9V03X 常见分辨率就是 188x120。code/ 下的算法统一用
 * SCUT_IMAGE_W / SCUT_IMAGE_H，不写死数字，所以换摄像头时
 * 只改这两行即可（例如换 160x120）。
 *
 * ★ 改完请同步确认 pic/ 里的测试图尺寸：不一致会被裁切或留黑。
 * ★ 编号与放法详见工程里的 pic/1/README-pic.txt（新建工程时自动生成）。
 * -------------------------------------------------------------------------- */
#define SCUT_IMAGE_W            (188)
#define SCUT_IMAGE_H            (120)

/* --------------------------------------------------------------------------
 * 测试图集
 *
 * 图片按 <SCUT_PIC_DIR>/<编号><SCUT_PIC_EXT> 读取，编号从 1 开始连续。
 * 支持的扩展名可写多个，用逗号分隔，按顺序优先匹配：
 *      #define SCUT_PIC_EXT   ".bmp,.png"
 *
 * ★ 下面两项只是【默认值】。日常改图集请用 VS Code 的设置界面
 *   （设置 → 搜索 "SCUT-71"），那里改完立即生效，不用重新编译：
 *       scut71.picDir        图集目录
 *       scut71.picExt        图后缀
 *       scut71.startFrame    从第几张开始
 *       scut71.advancePerFrame  是否每帧换下一张
 *   命令行的 --pic / --ext / --frame 同样会覆盖这里。
 *   保留宏定义是为了让环境脱离 IDE 也能跑（例如命令行批处理）。
 * -------------------------------------------------------------------------- */
#define SCUT_PIC_DIR            "pic/1"
#define SCUT_PIC_EXT            ".bmp"

/* --------------------------------------------------------------------------
 * 每帧重复调用 PROCESS 角色的次数
 *
 * 设为 1 = 正常运行。设大（如 100）可做复杂度测试：环境会把
 * 总耗时除以次数，得到「平均单次」的稳定读数，抵消计时抖动。
 *
 * ★ 同样是默认值；日常改这个用设置里的 scut71.processRepeat，
 *   或命令行 --repeat。改完不需要重新编译。
 * -------------------------------------------------------------------------- */
#define SCUT_PROCESS_REPEAT     (1)

#endif /* SCUT_CONFIG_H */
