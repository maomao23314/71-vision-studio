/* ==========================================================================
 *  camera.c —— 用户算法示例（★ 这是用户唯一需要改的文件）
 *  --------------------------------------------------------------------------
 *  设计理念对照：
 *    · 上手即用     → 整个工程只有这一个源文件需要动
 *    · 可移植       → 本文件【没有】任何仿真环境的注册代码，可原样拷进车载工程
 *    · 松耦合       → 环境调用哪三个函数，由「设置」决定，不写在这里
 *
 *  ★ 你不需要写 main()：环境已经有了。
 *  ★ 你不需要写 SCUT_INIT / SCUT_FRAME 之类的注册宏：
 *      环境调用哪几个函数由【插件的配置面板】指定（见下面「三个入口」）。
 *  ★ 你不需要声明想看哪些变量：环境会自动发现并列进面板让你勾选。
 *
 *  ★★ 为什么这个文件【故意】叫 camera.c 而不是 main.c（可移植性要求）
 *  --------------------------------------------------------------------------
 *    真车工程里承担「摄像头取图 + 图像处理」的那个编译单元就叫 camera.c，
 *    团队既有的 .c / 头文件 / 构建清单都是按这个名字引用的。
 *    仿真文件与车载文件同名、同职责，意味着你在这里调通的算法可以
 *    【原样拷进车载工程，一个字符都不用改、也不用改名】。
 *
 *    反过来说：如果这里默认叫 main.c，你在车载工程里就会有两个 main 的
 *    命名冲突（车载工程自己也有 main.c），必须手工改名 + 改 include，
 *    而改名这一步正是最容易漏掉、也最容易在临场出问题的地方。
 *    所以名字从一开始就和真车对齐 —— 这是硬性要求，请不要改回 main.c。
 * ========================================================================== */

#include "scut_sdk.h"

/* --------------------------------------------------------------------------
 * 三个入口（★ 唯一需要和插件"对上号"的地方）
 *
 * 填法：点侧边栏仿真视图工具栏最右边的 ⚙ 打开配置面板，
 *       在「钩子函数」那三栏里分别填下面这些函数名（每行一个）：
 *
 *     camera_init       →  「开机函数」        开机一次，不计时
 *     camera_process    →  「每帧处理函数」   ★ 每帧，计时段
 *     camera_draw       →  「每帧后处理函数」  每帧，不计时（画图/打日志）
 *     camera_report     →  「每帧后处理函数」  同上，可以填多个，按顺序调用
 *
 * ★ 这些值存在工程根的 scut_project.json 里（跟着工程走，能进 git）。
 *   ★ 不在 VS Code 的用户设置里 —— 那个位置 0.9.4 起就不再使用了。
 *
 * ★ 它们必须是【非 static】的 void f(void)。
 *   这不是额外限制 —— 车上 main() 要调用它们，本来就得如此。
 *   正因为要求一致，这个文件才能直接搬上车。
 * -------------------------------------------------------------------------- */

/* --------------------------------------------------------------------------
 * 算法用到的全局量
 *
 * ★ 这些变量【不需要注册】。环境会在构建时自动扫描调试信息，
 *   把它们列进变量面板，你勾选即可看到数值/曲线。
 *   只有自动发现覆盖不到的场景（例如运行期 malloc 的缓冲）才需要
 *   SCUT_Watch 主动注册 —— 那些会排在面板最前面并高亮。
 * -------------------------------------------------------------------------- */
int     g_threshold = 0;                        /* 二值化阈值 */
int     g_left_line[SCUT_IMAGE_H];              /* 每行左边界列坐标 */
int     g_right_line[SCUT_IMAGE_H];             /* 每行右边界列坐标 */
int     g_mid_line[SCUT_IMAGE_H];               /* 每行中线列坐标 */
int     g_lost_count = 0;                       /* 连续丢线行数 */
static int s_histogram[256];                    /* 灰度直方图（static 也能被发现） */

/* 结果图：环境会把它显示到"处理后的图像"里。
 * ★ 数组名要填到设置里的「结果图数组名」；留空则画面显示输入图本身。 */
unsigned char g_binary[SCUT_IMAGE_H][SCUT_IMAGE_W];

/* --------------------------------------------------------------------------
 * 输入图像
 *
 * ★ 环境提供了一个全局数组 mt9v03x_image[高][宽]（名字可在设置里改），
 *   地址【恒定不变】。像在车上那样直接读它即可 —— 本文件下面就是这么用的。
 *
 *   声明由环境自动提供（生成的 scut_config.h 里有 extern），
 *   所以你不需要自己写 extern，也不该自己再定义一份：
 *   多一份副本会破坏"地址恒定"，让逆透视这类指针表失效。
 * -------------------------------------------------------------------------- */

/* --------------------------------------------------------------------------
 * 初始化：开机一次，【不计时】
 *
 * 建表、标定、清缓冲这类一次性工作放这里最合适
 * （典型例子是逆透视的坐标映射表，只需建一次）。
 * -------------------------------------------------------------------------- */
void camera_init(void)
{
    int i;

    for (i = 0; i < SCUT_IMAGE_H; i++) {
        g_left_line[i]  = -1;                   /* -1 = 本行还没搜到 */
        g_right_line[i] = -1;
        g_mid_line[i]   = -1;
    }
    for (i = 0; i < 256; i++) {
        s_histogram[i] = 0;
    }
    for (i = 0; i < SCUT_IMAGE_H; i++) {
        int x;
        for (x = 0; x < SCUT_IMAGE_W; x++) {
            g_binary[i][x] = 0;
        }
    }
}

/* --------------------------------------------------------------------------
 * 每帧处理：★ 这是被计时的主体
 *
 * 注意：这里【只做算法】，不要在这里画图、不要 printf。
 *      画图和打日志请放到后处理函数 —— 车载程序上没有屏幕，
 *      把绘图算进算法耗时会让性能数据失真（实测能虚高好几倍）。
 * -------------------------------------------------------------------------- */
void camera_process(void)
{
    int w = SCUT_IMAGE_W;
    int h = SCUT_IMAGE_H;
    int x, y, i;
    long sum = 0;
    int thre;

    /* --- 1) 大津法求阈值（简化版：先统计直方图） --- */
    for (i = 0; i < 256; i++) {
        s_histogram[i] = 0;
    }
    for (y = 0; y < h; y++) {
        for (x = 0; x < w; x++) {
            s_histogram[mt9v03x_image[y][x]]++;
        }
    }

    /* 用总均值的一个比例当阈值：够用，且不引入浮点开销 */
    for (i = 0; i < 256; i++) {
        sum += (long)s_histogram[i] * i;
    }
    thre = (w > 0 && h > 0) ? (int)(sum / ((long)w * h) * 6 / 5) : 128;
    if (thre < 1)   { thre = 1; }
    if (thre > 255) { thre = 255; }
    g_threshold = thre;

    /* --- 2) 逐行找左右边界（最朴素的跳变检测） --- */
    g_lost_count = 0;
    for (y = h - 1; y >= 0; y--) {
        int left = -1, right = -1;

        for (x = 1; x < w - 1; x++) {
            int v  = mt9v03x_image[y][x];
            int vl = mt9v03x_image[y][x - 1];

            /* 黑 -> 白 跳变 = 左边界 */
            if (left < 0 && vl <= thre && v > thre) {
                left = x;
            }
            /* 白 -> 黑 跳变 = 右边界 */
            if (left >= 0 && right < 0 && vl > thre && v <= thre) {
                right = x;
            }
        }

        g_left_line[y]  = left;
        g_right_line[y] = right;

        if (left >= 0 && right > left) {
            g_mid_line[y] = (left + right) / 2;
        } else {
            g_mid_line[y] = -1;
            g_lost_count++;
        }
    }

    /* --- 3) 把二值化结果写进【自己的结果图】 ---
     *     注意：写的是 g_binary，不是"环境的输出图"。
     *     环境会按设置里的「结果图数组名」把它搬去显示。
     *     这样算法完全不知道"显示"这件事存在 —— 这正是可移植性的来源。 */
    for (y = 0; y < h; y++) {
        for (x = 0; x < w; x++) {
            g_binary[y][x] = (mt9v03x_image[y][x] > thre) ? 255 : 0;
        }
    }
}

/* --------------------------------------------------------------------------
 * 绘制：把中间结果画到【覆盖层】，★ 不计入处理时间
 *
 *  ★ 覆盖层是彩色的，输出图也是彩色的（RGB 三通道）。
 *   算法结果写进 g_binary 后由环境**原样显示**；调试标注画在覆盖层上，
 *   由调度器合成到输出图 —— 所以标注是彩色的，一眼可辨。
 *
 * ★ 在车载工程里，这个函数对应的就是"往 IPS 屏上画标注"，
 *   或者干脆删掉 —— 删掉不影响算法。
 *
 * ---------------------------------------------------------------------------
 *  ★ 四个绘图函数（都在 scut_draw.h 里，坐标越界会自动忽略，不用自己判断）
 * ---------------------------------------------------------------------------
 *      SCUT_DrawPoint(x, y, color)                  画一个像素
 *      SCUT_DrawLine (x0, y0, x1, y1, color)        画直线（Bresenham）
 *      SCUT_DrawRect (x0, y0, x1, y1, color)        画**空心**矩形（四条边）
 *      SCUT_DrawText (x, y, color, fmt, ...)        画 ASCII 文字，用法同 printf
 *
 *    ★ DrawText 只支持 ASCII（内置 8×8 字库），且**不要用它画读数** ——
 *      车上没有屏幕，"把数字画在图上"是不可移植的做法。
 *      要看数值请用 SCUT_Log 或变量面板。
 *
 * ---------------------------------------------------------------------------
 *  ★ 预定义颜色（12 个）
 * ---------------------------------------------------------------------------
 *      SCUT_COLOR_BLACK      SCUT_COLOR_WHITE      SCUT_COLOR_RED
 *      SCUT_COLOR_GREEN      SCUT_COLOR_BLUE       SCUT_COLOR_YELLOW
 *      SCUT_COLOR_CYAN       SCUT_COLOR_MAGENTA    SCUT_COLOR_ORANGE
 *      SCUT_COLOR_GRAY       SCUT_COLOR_LIGHTGRAY
 *      （用高对比、彼此好区分的几个就够；下面 camera_draw 用了红/绿/蓝）
 *
 * ---------------------------------------------------------------------------
 *  ★ 自建颜色：用 SCUT_RGB(r, g, b)，每个分量 0..255
 * ---------------------------------------------------------------------------
 *      scut_u32 my_color = SCUT_RGB(255, 128, 0);      // 橙色
 *      SCUT_DrawLine(0, 0, 10, 10, my_color);
 *
 *    ★ 颜色内部是 0x00BBGGRR（与 Windows COLORREF 一致，便于老代码迁移），
 *      所以**不要手写十六进制字面量** —— 0xFF0000 是**蓝色**不是红色。
 *      一律用 SCUT_RGB(r,g,b) 或上面的预定义名，顺序就不会记错。
 *
 *    ★ 灰度也可以用同一个宏：SCUT_RGB(v, v, v)。
 *      例如把灰度图叠到覆盖层上时：SCUT_RGB(g, g, g)。
 * -------------------------------------------------------------------------- */
void camera_draw(void)
{
    int y;
    int h = SCUT_GetOutputHeight();

    for (y = 0; y < h && y < SCUT_IMAGE_H; y++) {
        if (g_left_line[y] >= 0) {
            SCUT_DrawPoint(g_left_line[y],  y, SCUT_COLOR_RED);
        }
        if (g_right_line[y] >= 0) {
            SCUT_DrawPoint(g_right_line[y], y, SCUT_COLOR_GREEN);
        }
        if (g_mid_line[y] >= 0) {
            SCUT_DrawPoint(g_mid_line[y],   y, SCUT_COLOR_BLUE);
        }
    }

    /* 自建颜色的例子：在画面上方标一条橙色横线（用 SCUT_RGB 而不是字面量）。 */
    SCUT_DrawLine(0, 2, SCUT_IMAGE_W - 1, 2, SCUT_RGB(255, 128, 0));

    /* DrawText 的例子（ASCII only）。注意不要拿它当"数据显示"用，见上。 */
    SCUT_DrawText(2, 6, SCUT_COLOR_YELLOW, "lost=%d", g_lost_count);
}

/* --------------------------------------------------------------------------
 * 数据输出：★ 不计入处理时间
 *
 * ★ 这里【只写】需要额外组合判断的东西。
 *   想直接看某个变量（比如 g_threshold、g_left_line），
 *   在变量面板里勾选即可，不用在这里打印。
 *
 * ★ 输出的内容会出现在 VS Code 的「SCUT-71 运行日志」输出面板里
 *   （可搜索、可复制、不占侧边栏）。
 * -------------------------------------------------------------------------- */
void camera_report(void)
{
    SCUT_Log(SCUT_LOG_INFO, "阈值=%d  丢线=%d 行", g_threshold, g_lost_count);
}
