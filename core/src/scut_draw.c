/* ==========================================================================
 *  内部状态
 *  --------------------------------------------------------------------------
 *  ★ 全部零初始化（静态存储期保证）。零初始化 = 「未绑定」，
 *    这正是我们要的语义：任何绘制在任何绑定之前都必须安全地什么都不做。
 * ========================================================================== */
static scut_u8  *s_gray    = NULL;   /* 输出图（RGB 三字节/像素，PROCESS 写、绘制不写） */
static scut_u32 *s_overlay = NULL;   /* 彩色覆盖层（绘制唯一目标） */
static int       s_w       = 0;      /* 宽度（列数，单位：像素） */
static int       s_h       = 0;      /* 高度（行数） */
/* 行步长，单位【不同】，必须分开存 —— 这是本文件最容易出错的地方：
 *     s_ovl_stride : 覆盖层的行步长，单位是 u32 元素数（每像素 1 个 u32）→ 宽
 *     s_rgb_stride : 输出图的行步长，单位是【字节】（每像素 3 字节）→ 宽 × 3
 *   之前输出图是单通道灰度，两者步长相同，共用一个 s_stride 就够了；
 *   改成 RGB 之后两者【不再相等】，若继续共用一个，
 *   要么覆盖层越界（步长偏小），要么 RGB 每隔一行就错位（步长偏大）——
 *   后者画面是「正常」的条纹状错位，不崩不报错，最难查。 */
static int       s_ovl_stride = 0;
static int       s_rgb_stride = 0;

/* --------------------------------------------------------------------------
 *  「本帧是否已被算法写过输出图」标志
 *
 *  ★ 为什么需要它（一条真实的接口缺口）：
 *    scut_sdk.h 明确把 SCUT_OutImageSet / SetRGB 宣传为"算法直接产出显示图"
 *    的路径。但调度器每帧在 PROCESS 之后、DRAW 之前会调
 *    scut_env_seed_output_from_input() 把输入图铺满输出图 ——
 *    于是算法在 PROCESS 里用 SCUT_OutImageSet 画的像素，会被这一铺【全量冲掉】。
 *    用户看到的是"我明明写了 OutImageSet，画面却还是原始灰度图"，
 *    不报错、不崩溃，只是他写的东西没了。
 *
 *  ★ 修法为什么放在这里（拥有输出图的模块）而不是 scut_input.c：
 *    "输出图有没有被写过"这件事，只有写它的人（本模块）知道。
 *    让 scut_input.c 去问 scut_draw.c，是调用方向正确的依赖；
 *    反过来（让 draw 去改 seed 的行为）会把帧序逻辑摊到两个模块里。
 *    由调度器读这个标志再决定要不要 seed —— 帧序仍然只有调度器说了算。
 *
 *  ★ 语义：只在 SCUT_OutImageSet / SetRGB 真正【写入了一个像素】时置 1。
 *    越界调用不算（它什么都没写）。
 *    由调度器在每帧开头清零（见 scut_sched.c 的 run_one_frame）。
 *
 *  ★ 为什么不是"清零 + 检查"分散在各处：
 *    散着写就要求每个写入点都记得置位，漏一个就是一次静默失效 ——
 *    所以两个写入函数都置位，且只有调度器清零，职责单一。
 * -------------------------------------------------------------------------- */
static int s_out_written = 0;

/* 本帧是否已被算法直接写过输出图。供调度器决定"要不要铺默认底图"。 */
int scut_draw_output_written(void)
{
    return s_out_written;
}

/* 由调度器在每帧开头调用，开始新一帧的记账。 */
void scut_draw_clear_output_written(void)
{
    s_out_written = 0;
}

/* 由 scut_input.c 的写入通路在真正写入后调用（见 scut_draw.h 的说明）。
 * ★ 0.10.6 起 SCUT_OutImageSet / SCUT_EnvCopyOutput 带"选哪块图"的参数，
 *   写入代码统一收在 scut_input.c（两块图共用一段），所以置位也从那里转告，
 *   本模块不再自己持有那两个函数 —— 记账点只有一个。 */
void scut_draw_mark_output_written(void)
{
    s_out_written = 1;
}

