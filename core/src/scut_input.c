/* ==========================================================================
 *  scut_input.c —— 输入图像访问器与阶段门控
 *  --------------------------------------------------------------------------
 *  设计理念对照：
 *    · 模拟单片机   → 输入图像就是摄像头数组，车载工程可换成自己的
 *    · 适应任意代码 → 用访问器而不是裸数组，防呆而不限制正常用法
 *
 *  ★ 为什么要有「阶段门控」（相对旧环境的重要改进）
 *  ---------------------------------------------------------------------------
 *  需求方提出的顾虑：用户可能在【绘制回调】里做真正的图像处理，
 *  从而把耗时算到不计时的区域里，让性能数据变得没有意义。
 *
 *  旧环境的做法是：把输入图像做成裸的全局数组，任何人都能直接访问，
 *  因此【无法阻止】这种行为。
 *
 *  本实现的做法：
 *    1) PROCESS 阶段：SCUT_GetInputImage() 返回有效指针
 *    2) DRAW / REPORT 阶段：返回 NULL，并记一次违规
 *    3) 违规次数会显示在日志里，让「把处理写进绘制」立刻暴露
 *
 *  ★ 诚实边界（必须写清楚，不要过度承诺）
 *  ---------------------------------------------------------------------------
 *  C 语言里无法 100% 阻止蓄意绕过：如果环境仍暴露了裸数组符号，
 *  用户可以直接访问它。因此要 100% 生效，还需要配合「拆编译单元」
 *  并限制符号可见性。
 *  但对【无意误用】（没意识到绘制阶段不该做处理），访问器能挡住绝大多数。
 *  这是刻意选择的性价比：低成本、高覆盖。
 * ========================================================================== */

#include "scut_sdk.h"
#include "scut_internal.h"

#include <stdio.h>

/* --- 由 bind 单元提供 --- */
extern scut_u8 *scut_bind_input(void);
extern int      scut_bind_width(void);
extern int      scut_bind_height(void);

/* --------------------------------------------------------------------------
 * 当前阶段
 *
 * ★ 阶段枚举定义在 scut_internal.h（核心内部共享），不在这里重复定义。
 *   曾经这里自己定义过一份，结果 scut_sched.c 用的是另一份 ——
 *   两处枚举"看起来一样"但编译器认为是不同类型，直接编译失败。
 *   共享定义是唯一正确的做法。
 * -------------------------------------------------------------------------- */
static scut_phase_t s_phase = SCUT_PHASE_IDLE;
static int          s_violations = 0;   /* 在非法阶段访问输入图像的次数 */

/* 供 scut_sched.c 调用。 */
void scut_input_set_phase(int phase)
{
    s_phase = (scut_phase_t)phase;
}

int scut_input_violations(void)
{
    return s_violations;
}

void scut_input_reset_violations(void)
{
    s_violations = 0;
}

/* --------------------------------------------------------------------------
 * 输入图像访问器
 *
 * ★ 行步长 = 宽度（单通道连续存放）：
 *       pixel(y, x) = img[y * w + x]
 *   这一点必须让用户知道，所以写进注释和文档。
 * -------------------------------------------------------------------------- */
const scut_u8 *SCUT_GetInputImage(int *w, int *h)
{
    /* 只有 PROCESS 阶段（以及 PRE_FRAME，因为它也是"处理前"的准备阶段）
     * 允许访问输入图像。
     *
     * ★ 为什么 PRE_FRAME 也允许：
     *   它的语义就是"每帧处理前的准备"，属于计时区间内的处理逻辑，
     *   允许访问是合理的。而 DRAW / REPORT 是明确的"输出"阶段，
     *   在那里读输入图像几乎总是用错了地方。 */
    if (s_phase != SCUT_PHASE_PROCESS && s_phase != SCUT_PHASE_PRE_FRAME) {
        s_violations++;

        /* 只在第一次违规时提示，避免刷屏。
         * ★ 这条日志走 stderr 而不是 SCUT_Log：
         *   违规发生的时刻恰恰不在 REPORT 阶段，SCUT_Log 会被门控挡掉，
         *   用它反而看不到提示。这是一个容易忽略的自指陷阱。 */
        if (s_violations == 1) {
            fprintf(stderr,
                "[scut] 警告: 在非处理阶段调用了 SCUT_GetInputImage()。\n"
                "       输入图像只在 PRE_FRAME / PROCESS 阶段可访问。\n"
                "       如果在绘制或日志回调里做图像处理，算法耗时不会被计入，\n"
                "       性能数据将失去意义。请把处理逻辑移到 PROCESS 回调。\n");
        }
        return 0;
    }

    if (w != 0) { *w = scut_bind_width(); }
    if (h != 0) { *h = scut_bind_height(); }
    return scut_bind_input();
}
